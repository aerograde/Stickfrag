#!/usr/bin/env python3
"""Build the mirror's fast delivery artefacts.

- concatenates the 13 game stylesheets into one file (same cascade order)
- rewrites the stylesheet hash in play/index.html
- writes .br and .gz next to every text asset for tools/serve.py

    python3 tools/build.py
    python3 tools/build.py --force
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "stickfrag.com"
PLAY = SITE / "play"

# Exact order from play/index.html: the cascade depends on it.
CSS_FILES = [
    "game-hud.css",
    "game-minimap.css",
    "game-ctf.css",
    "game-bomb.css",
    "game-hardpoint.css",
    "game-chat.css",
    "game-menu.css",
    "game-results.css",
    "game-loadout.css",
    "game-screens.css",
    "game-emote.css",
    "game-touch.css",
    "daily.css",
]
COMPRESSIBLE = {".html", ".css", ".js", ".mjs", ".json", ".svg", ".txt", ".map"}


def bundle_css() -> Path:
    out = SITE / "game.all.css"
    parts = [
        "/* GENERATED by tools/build.py. Edit the source files, not this file. */\n",
        f"/* Cascade order: {', '.join(CSS_FILES)} */\n",
    ]
    for name in CSS_FILES:
        source = SITE / name
        if not source.is_file():
            raise SystemExit(f"missing stylesheet: {source}")
        parts.append(f"\n/* ==== {name} ==== */\n")
        parts.append(source.read_text(encoding="utf-8"))
        if not parts[-1].endswith("\n"):
            parts.append("\n")
    out.write_text("".join(parts), encoding="utf-8")
    return out


def update_html(bundle: Path) -> str:
    digest = hashlib.sha256(bundle.read_bytes()).hexdigest()[:10]
    html_path = PLAY / "index.html"
    html = html_path.read_text(encoding="utf-8")
    updated, count = re.subn(r'href="/game\.all\.css\?v=[0-9a-f]+"', f'href="/game.all.css?v={digest}"', html)
    if count == 0:
        print("warning: index.html has no game.all.css link to update")
    elif updated != html:
        html_path.write_text(updated, encoding="utf-8")
    return digest


def compress(path: Path, force: bool) -> tuple[int, int, int]:
    raw = path.read_bytes()
    brotli_path = path.with_name(path.name + ".br")
    gzip_path = path.with_name(path.name + ".gz")
    brotli_size = 0
    gzip_size = 0

    need = (
        force
        or not brotli_path.is_file()
        or int(brotli_path.stat().st_mtime) < int(path.stat().st_mtime)
    )
    if need and shutil.which("brotli"):
        subprocess.run(["brotli", "-q", "11", "-f", "-o", str(brotli_path), str(path)], check=True)
    if brotli_path.is_file():
        brotli_size = brotli_path.stat().st_size

    need = (
        force
        or not gzip_path.is_file()
        or int(gzip_path.stat().st_mtime) < int(path.stat().st_mtime)
    )
    if need:
        gzip_path.write_bytes(gzip.compress(raw, compresslevel=9, mtime=0))
    if gzip_path.is_file():
        gzip_size = gzip_path.stat().st_size

    return len(raw), brotli_size, gzip_size


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force", action="store_true", help="rebuild every compressed file")
    parser.add_argument("--no-compress", action="store_true", help="only refresh the CSS bundle")
    args = parser.parse_args()

    bundle = bundle_css()
    digest = update_html(bundle)
    print(f"game.all.css  v={digest}  {bundle.stat().st_size:,} bytes")

    if args.no_compress:
        return

    if not shutil.which("brotli"):
        raise SystemExit("brotli is required (brew install brotli)")

    files = [
        path
        for path in SITE.rglob("*")
        if path.is_file()
        and path.suffix.lower() in COMPRESSIBLE
        and not path.name.endswith((".br", ".gz"))
    ]
    rows = []
    for path in sorted(files):
        raw, br, gz = compress(path, args.force)
        if raw > 50_000:
            rows.append((path.relative_to(SITE), raw, br, gz))

    print(f"compressed {len(files)} text assets")
    for name, raw, br, gz in sorted(rows, key=lambda row: row[1], reverse=True)[:10]:
        print(f"  {str(name):34} {raw:>9,}  br {br:>9,}  gz {gz:>9,}")


if __name__ == "__main__":
    main()
